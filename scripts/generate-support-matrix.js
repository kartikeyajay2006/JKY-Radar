/** @import { AnalysisOptions } from '@jky/radar-core' */
/**
 * Generates docs/SUPPORT_MATRIX.md and docs/RULE_CATALOG.md from the actual capability
 * registry, rule registry and fixture runs. Run: npm run docs:matrix
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { analyzeContracts, capabilityReport } from '@jky/radar-adapters';
import {
  ENGINE_VERSION,
  PROTOCOL_LABEL,
  RULE_REGISTRY_VERSION,
  ruleRegistry,
  SEVERITY_LABEL,
} from '@jky/radar-core';

/**
 * @typedef {Object} Entry
 * @property {string} id
 * @property {string} name
 * @property {string} baseline
 * @property {string} candidate
 * @property {AnalysisOptions} [options]
 * @property {{ gate: string }} expect
 */
const manifest = /** @type {Entry[]} */ (JSON.parse(readFileSync('fixtures/manifest.json', 'utf8')));
/** @param {string} p */
const fx = (p) => readFileSync(`fixtures/${p}`, 'utf8');

/** @type {string[]} */
const L = [];
L.push('# Support matrix', '');
L.push(
  `Generated by \`npm run docs:matrix\` from the running code (engine ${ENGINE_VERSION}, rule registry ${RULE_REGISTRY_VERSION}). Do not edit by hand.`,
  '',
);
L.push(
  'Status values: **supported** (parsed, compared and classified with tested rules), **partial** (works with stated gaps), **experimental** (works, limited validation), **unsupported** (detected and rejected with an explanation).',
  '',
);
L.push(
  '| Capability | Versions | Status | Parse | Semantic diff | Classification | Tested rules | Release |',
);
L.push('| --- | --- | --- | --- | --- | --- | ---: | --- |');
for (const c of capabilityReport()) {
  L.push(
    `| ${c.label} | ${c.versions} | **${c.status}** | ${c.levels.parse} | ${c.levels.semanticDiff} | ${c.levels.classification} | ${c.protocol && c.rules.registered ? `${c.rules.tested}/${c.rules.registered}` : '—'} | ${c.release} |`,
  );
}
L.push('', '## Notes per capability', '');
for (const c of capabilityReport()) {
  L.push(`### ${c.label}`, '');
  for (const n of c.notes) L.push(`- ${n}`);
  L.push('');
}
L.push(
  '## Fixture evidence',
  '',
  'Each pair below is analysed in CI (`packages/radar-adapters/test/fixtures.test.ts`) and must reproduce the expected gate.',
  '',
);
L.push('| Fixture pair | Gate | Coverage | Findings | Breaking |');
L.push('| --- | --- | --- | ---: | ---: |');
for (const m of manifest) {
  const out = analyzeContracts({
    baseline: { content: fx(m.baseline), fileName: m.baseline },
    candidate: { content: fx(m.candidate), fileName: m.candidate },
    options: m.options ?? {},
  });
  if (out.ok === false) {
    L.push(`| ${m.name} | ERROR ${out.code} | | | |`);
    continue;
  }
  const r = out.result;
  L.push(
    `| ${m.name} (\`${m.baseline}\` → \`${m.candidate}\`) | ${r.gate.decision} | ${r.coverage.level} | ${r.findings.length} | ${r.gate.counts.breaking} |`,
  );
}
writeFileSync('docs/SUPPORT_MATRIX.md', `${L.join('\n')}\n`);

/** @type {string[]} */
const R = [];
R.push('# Rule catalog', '');
R.push(
  `Generated from the rule registry ${RULE_REGISTRY_VERSION} by \`npm run docs:matrix\`. ${ruleRegistry.all().length} rules. Rule IDs are immutable; severity is fixed per rule.`,
  '',
);
R.push(
  'Every rule marked tested has a positive case (the rule fires) and a negative near-miss case (it must not fire) in `packages/radar-adapters/test/rule-cases.ts`; `rules.test.ts` fails if a tested rule lacks cases.',
  '',
);
const groups =
  /** @type {Map<string, typeof ruleRegistry extends { all(): readonly (infer T)[] } ? T[] : never>} */ (
    new Map()
  );
for (const r of ruleRegistry.all()) {
  const key =
    r.protocols.length > 3
      ? 'Schema rules (OpenAPI, Swagger, manual REST, JSON Schema, AsyncAPI payloads)'
      : r.protocols.map((p) => PROTOCOL_LABEL[p]).join(', ');
  groups.set(key, [...(groups.get(key) ?? []), r]);
}
for (const [g, rules] of groups) {
  R.push(`## ${g}`, '');
  R.push('| Rule | Severity | When it fires | Why it is risky | Recommended fix | Tested |');
  R.push('| --- | --- | --- | --- | --- | --- |');
  for (const r of rules) {
    /** @param {string} s */
    const esc = (s) => s.replace(/\|/g, '\\|');
    R.push(
      `| \`${r.id}\` — ${r.title} | ${SEVERITY_LABEL[r.severity]} | ${esc(r.description)} | ${esc(r.impact)} | ${esc(r.recommendation)} | ${r.tested ? 'yes' : 'no (safety net)'} |`,
    );
  }
  R.push('');
}
writeFileSync('docs/RULE_CATALOG.md', `${R.join('\n')}\n`);
console.log(
  `Wrote docs/SUPPORT_MATRIX.md and docs/RULE_CATALOG.md (${ruleRegistry.all().length} rules, ${manifest.length} fixture pairs)`,
);
